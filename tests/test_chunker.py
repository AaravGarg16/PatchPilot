from retrieval.chunker import MAX_CHUNK_LINES, chunk_file

SOURCE = '''"""Module doc."""
import math

RATE = 3


@cache
def top(a):
    return a


class Cart:
    """A cart."""

    items: list

    def add(self, x):
        self.items.append(x)

    async def total(self):
        return sum(self.items)


if __name__ == "__main__":
    top(1)
'''


def labels(chunks):
    return [(c.chunk_type, c.symbol, c.start_line, c.end_line) for c in chunks]


def test_python_chunks_follow_symbols():
    assert labels(chunk_file("shop/cart.py", SOURCE)) == [
        ("module", None, 1, 4),
        ("function", "top", 7, 9),
        ("class", "Cart", 12, 16),
        ("method", "Cart.add", 17, 18),
        ("method", "Cart.total", 20, 21),
        ("module", None, 24, 25),
    ]


def test_decorators_stay_with_their_function():
    (function,) = [c for c in chunk_file("shop/cart.py", SOURCE) if c.symbol == "top"]
    assert function.content.startswith("@cache\ndef top")


def test_long_functions_are_split_but_keep_their_symbol():
    body = "\n".join(f"    x{i} = {i}" for i in range(MAX_CHUNK_LINES + 30))
    chunks = chunk_file("big.py", f"def big():\n{body}\n")
    assert [(c.symbol, c.start_line) for c in chunks] == [("big", 1), ("big", MAX_CHUNK_LINES + 1)]


def test_unparseable_python_falls_back_to_line_windows():
    chunks = chunk_file("broken.py", "def broken(:\n    pass\n")
    assert labels(chunks) == [("text", None, 1, 2)]


def test_markdown_splits_on_headings_but_not_inside_code_fences():
    md = "# Title\nintro\n\n## Install\n```\n# not a heading\n```\n## Usage\nrun it\n"
    assert labels(chunk_file("README.md", md)) == [
        ("doc_section", "Title", 1, 3),
        ("doc_section", "Install", 4, 7),
        ("doc_section", "Usage", 8, 9),
    ]


def test_config_files_are_one_block_and_unknown_files_are_skipped():
    assert labels(chunk_file("pytest.ini", "[pytest]\ntestpaths = tests\n")) == [("config", None, 1, 2)]
    assert chunk_file("logo.png", "binary-ish") == []
    assert chunk_file("empty.py", "\n\n") == []


def test_data_files_with_huge_lines_are_not_indexed():
    assert chunk_file("tests/data/raster.txt", "1 2 3 " * 2000 + "\n") == []
    assert chunk_file("tests/data/geometries.json", '{"a": [' + "1, " * 1000 + "1]}\n") == []


def test_noise_is_classified():
    from retrieval.chunker import skip_reason

    assert skip_reason("app/migrations/0001_initial.py", "# Generated by Django 3.2 on 2021\nimport x\n") == "generated"
    assert skip_reason("tests/fixtures/users.json", '{"id": 1}\n') == "data"
    assert skip_reason("tests/data/raster.txt", "1 2 3\n") == "data"
    assert skip_reason("data/blob.json", "x" * 3000) == "long_lines"
    assert skip_reason("big.py", "x = 1\n" * 50_000) == "too_large"
    # Code and docs under test dirs, and config at the root, are kept.
    for path in ("tests/test_views.py", "tests/README.md", "docs/index.rst", "pyproject.toml", "app/models.py"):
        assert skip_reason(path, "x = 1\n") is None, path


def test_noise_still_chunks_when_counting():
    text = "# Generated by Django 3.2\nimport x\n"
    assert chunk_file("app/migrations/0001_initial.py", text) == []
    assert len(chunk_file("app/migrations/0001_initial.py", text, keep_noise=True)) == 1


def test_docs_are_never_data_even_under_a_testing_section():
    from retrieval.chunker import skip_reason

    assert skip_reason("docs/topics/testing/advanced.txt", "Advanced testing topics\n") is None
    assert skip_reason("tests/testing/notes.txt", "1 2 3\n") == "data"
